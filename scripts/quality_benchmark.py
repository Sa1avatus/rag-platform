"""Quality + Performance benchmark: E5-small vs BGE-M3.

Runs inside the worker container:
  python /tmp/quality_benchmark.py

Loads the evaluation dataset generated by generate_eval_dataset.py,
runs pure vector retrieval for both models on the same corpus, and
computes Recall@K, MRR@K, nDCG@K with bootstrap 95% confidence
intervals, plus full latency profiling.
"""

from __future__ import annotations

import json
import math
import sys
import time

import numpy as np
import psycopg2

sys.path.insert(0, "/usr/local/lib/python3.12/site-packages")

from rag_platform.core.config import get_settings
from rag_platform.core.embedding_registry import get_model_by_id
from rag_platform.worker.embeddings import _load_model

# ── Configuration ──────────────────────────────────────────────────────

EVAL_DATASET_PATH = "/tmp/eval_dataset_v1.json"
OUTPUT_PATH = "/tmp/benchmark_results_v1.json"

PROJECT_ID = "9f6f0f20-24e3-4f8c-83a6-d97d3c62dc00"
OWNER_USER_ID = "bad20767-dfd5-4b81-9c13-fe92034a32e1"
COLLECTIONS = ["vacancies", "resumes", "profiles"]

K_VALUES = [5, 10, 20]
VECTOR_TOP_K = 30  # retrieve this many, then evaluate at various K

PERF_WARMUP = 5
PERF_RUNS = 3  # multi-run for stability
PERF_QUERIES = 20  # subset for performance benchmark

BOOTSTRAP_N = 1000
BOOTSTRAP_CI = 0.95

# ── Metric functions ──────────────────────────────────────────────────


def recall_at_k(
    retrieved: list[str], relevant: set[str], k: int,
) -> float:
    if not relevant:
        return 0.0
    hits = len(set(retrieved[:k]) & relevant)
    return hits / len(relevant)


def mrr_at_k(retrieved: list[str], relevant: set[str], k: int) -> float:
    for rank, item in enumerate(retrieved[:k], 1):
        if item in relevant:
            return 1.0 / rank
    return 0.0


def ndcg_at_k(
    retrieved: list[str],
    relevance_grades: dict[str, int],
    k: int,
) -> float:
    gains = [relevance_grades.get(item, 0) for item in retrieved[:k]]
    dcg = sum(
        (2 ** grade - 1) / math.log2(rank + 1)
        for rank, grade in enumerate(gains, 1)
    )
    ideal = sorted(
        (g for g in relevance_grades.values() if g > 0), reverse=True,
    )[:k]
    idcg = sum(
        (2 ** grade - 1) / math.log2(rank + 1)
        for rank, grade in enumerate(ideal, 1)
    )
    return dcg / idcg if idcg > 0 else 0.0


def bootstrap_ci(
    values: list[float],
    n_bootstrap: int = BOOTSTRAP_N,
    ci: float = BOOTSTRAP_CI,
) -> tuple[float, float, float]:
    """Return (mean, ci_low, ci_high) via bootstrap."""
    arr = np.array(values)
    n = len(arr)
    if n == 0:
        return 0.0, 0.0, 0.0
    rng = np.random.default_rng(42)
    boot_means = np.array([
        arr[rng.integers(0, n, size=n)].mean()
        for _ in range(n_bootstrap)
    ])
    alpha = (1 - ci) / 2
    lo = float(np.percentile(boot_means, alpha * 100))
    hi = float(np.percentile(boot_means, (1 - alpha) * 100))
    return float(arr.mean()), lo, hi


def percentile(values: list[float], p: float) -> float:
    if not values:
        return 0.0
    ordered = sorted(values)
    idx = max(0, math.ceil(len(ordered) * p) - 1)
    return ordered[idx]


# ── Embedding helper ──────────────────────────────────────────────────


def embed_query(
    query: str,
    cfg: object,
    session: object,
    tokenizer: object,
) -> list[float]:
    text = (cfg.query_prefix + query) if cfg.query_prefix else query
    inputs = tokenizer(
        [text], padding=True, truncation=True,
        max_length=cfg.max_input_tokens, return_tensors="np",
    )
    valid = {inp.name for inp in session.get_inputs()}
    ort_inputs = {k: v for k, v in inputs.items() if k in valid}
    if "token_type_ids" in valid and "token_type_ids" not in ort_inputs:
        ort_inputs["token_type_ids"] = np.zeros_like(inputs["input_ids"])
    outputs = session.run(None, ort_inputs)
    mask = np.expand_dims(inputs["attention_mask"], axis=-1)
    pooled = np.sum(outputs[0] * mask, axis=1) / np.clip(
        mask.sum(axis=1), a_min=1e-9, a_max=None,
    )
    norms = np.linalg.norm(pooled, axis=1, keepdims=True)
    vec = (pooled / norms)[0].tolist()
    return cfg.pad_vector(vec)


# ── Vector search helper ──────────────────────────────────────────────


def vector_search(
    cur: object,
    model_name: str,
    query_vec: list[float],
    top_k: int = VECTOR_TOP_K,
) -> list[str]:
    vec_str = "[" + ",".join(str(x) for x in query_vec) + "]"
    cur.execute(
        """
        SELECT c.id::text
        FROM chunk_embeddings ce
        JOIN chunks c ON c.id = ce.chunk_id
        WHERE ce.model = %s
          AND c.project_id = %s
          AND c.owner_user_id = %s
          AND c.collection = ANY(%s)
        ORDER BY ce.embedding <=> %s::vector
        LIMIT %s
        """,
        (
            model_name, PROJECT_ID, OWNER_USER_ID,
            COLLECTIONS, vec_str, top_k,
        ),
    )
    return [row[0] for row in cur.fetchall()]


# ── Jaccard overlap ───────────────────────────────────────────────────


def jaccard(a: list[str], b: list[str], k: int) -> float:
    sa = set(a[:k])
    sb = set(b[:k])
    if not sa and not sb:
        return 1.0
    union = sa | sb
    if not union:
        return 0.0
    return len(sa & sb) / len(union)


# ── Main ──────────────────────────────────────────────────────────────


def main():
    # Load evaluation dataset
    with open(EVAL_DATASET_PATH, encoding="utf-8") as f:
        dataset = json.load(f)

    queries_data = dataset["queries"]
    print(f"Loaded evaluation dataset: {len(queries_data)} queries")
    print(f"Corpus: {dataset['corpus']['total_chunks']} chunks")

    settings = get_settings()
    conn = psycopg2.connect(settings.database_url.replace("+asyncpg", ""))
    conn.autocommit = True
    cur = conn.cursor()

    # Load both models
    model_components = {}
    for model_id in ["multilingual-e5-small", "bge-m3"]:
        cfg = get_model_by_id(model_id)
        print(f"Loading {cfg.model_name} (dim={cfg.dimension})...")
        ort_session, tokenizer, device = _load_model(cfg)
        model_components[model_id] = {
            "cfg": cfg,
            "session": ort_session,
            "tokenizer": tokenizer,
            "device": device,
        }
        print(f"  Loaded. Device={device}")

    e5 = model_components["multilingual-e5-small"]
    bge = model_components["bge-m3"]

    # ── Quality benchmark ──────────────────────────────────────────────
    print(f"\n{'='*80}")
    print(f"QUALITY BENCHMARK: {len(queries_data)} queries × 2 models")
    print(f"{'='*80}\n")

    # Per-query results for both models
    e5_per_query: dict[str, dict[str, list[float]]] = {
        f"Recall@{k}": [] for k in K_VALUES
    }
    e5_per_query.update({f"MRR@{k}": [] for k in K_VALUES})
    e5_per_query.update({f"nDCG@{k}": [] for k in K_VALUES})
    bge_per_query: dict[str, dict[str, list[float]]] = {
        f"Recall@{k}": [] for k in K_VALUES
    }
    bge_per_query.update({f"MRR@{k}": [] for k in K_VALUES})
    bge_per_query.update({f"nDCG@{k}": [] for k in K_VALUES})

    e5_latency_embed: list[float] = []
    e5_latency_search: list[float] = []
    e5_latency_total: list[float] = []
    bge_latency_embed: list[float] = []
    bge_latency_search: list[float] = []
    bge_latency_total: list[float] = []

    e5_all_retrieved: list[list[str]] = []
    bge_all_retrieved: list[list[str]] = []

    for qi, qdata in enumerate(queries_data):
        query = qdata["query"]
        relevance = {
            str(cid): int(g) for cid, g in qdata["relevance_grades"].items()
        }
        relevant_ids = {cid for cid, g in relevance.items() if g > 0}

        if not relevant_ids:
            continue  # skip queries with no relevant docs

        # E5 retrieval
        t0 = time.perf_counter()
        e5_vec = embed_query(query, e5["cfg"], e5["session"], e5["tokenizer"])
        t1 = time.perf_counter()
        e5_ids = vector_search(cur, e5["cfg"].model_name, e5_vec)
        t2 = time.perf_counter()

        e5_latency_embed.append((t1 - t0) * 1000)
        e5_latency_search.append((t2 - t1) * 1000)
        e5_latency_total.append((t2 - t0) * 1000)
        e5_all_retrieved.append(e5_ids)

        # BGE retrieval
        t0 = time.perf_counter()
        bge_vec = embed_query(
            query, bge["cfg"], bge["session"], bge["tokenizer"],
        )
        t1 = time.perf_counter()
        bge_ids = vector_search(cur, bge["cfg"].model_name, bge_vec)
        t2 = time.perf_counter()

        bge_latency_embed.append((t1 - t0) * 1000)
        bge_latency_search.append((t2 - t1) * 1000)
        bge_latency_total.append((t2 - t0) * 1000)
        bge_all_retrieved.append(bge_ids)

        # Compute metrics at each K
        for k in K_VALUES:
            e5_per_query[f"Recall@{k}"].append(
                recall_at_k(e5_ids, relevant_ids, k),
            )
            e5_per_query[f"MRR@{k}"].append(
                mrr_at_k(e5_ids, relevant_ids, k),
            )
            e5_per_query[f"nDCG@{k}"].append(
                ndcg_at_k(e5_ids, relevance, k),
            )
            bge_per_query[f"Recall@{k}"].append(
                recall_at_k(bge_ids, relevant_ids, k),
            )
            bge_per_query[f"MRR@{k}"].append(
                mrr_at_k(bge_ids, relevant_ids, k),
            )
            bge_per_query[f"nDCG@{k}"].append(
                ndcg_at_k(bge_ids, relevance, k),
            )

        if (qi + 1) % 10 == 0:
            print(f"  Processed {qi + 1}/{len(queries_data)} queries")

    n_queries = len(e5_latency_embed)
    print(f"\nProcessed {n_queries} queries with relevant documents")

    # ── Aggregate metrics with bootstrap CI ────────────────────────────
    print(f"\n{'='*80}")
    print("QUALITY METRICS (with 95% bootstrap CI)")
    print(f"{'='*80}\n")

    header = (
        f"{'Metric':<15} {'E5 mean':>8} {'E5 CI':>18} "
        f"{'BGE mean':>9} {'BGE CI':>18} {'Δ':>7} {'Winner':>8}"
    )
    print(header)
    print("-" * len(header))

    quality_results = {}
    for metric_name in list(e5_per_query.keys()):
        e5_vals = e5_per_query[metric_name]
        bge_vals = bge_per_query[metric_name]
        e5_mean, e5_lo, e5_hi = bootstrap_ci(e5_vals)
        bge_mean, bge_lo, bge_hi = bootstrap_ci(bge_vals)
        delta = bge_mean - e5_mean

        # Determine winner: if CIs overlap, it's a tie
        if e5_lo > bge_hi:
            winner = "E5"
        elif bge_lo > e5_hi:
            winner = "BGE"
        else:
            winner = "~"

        e5_ci_str = f"[{e5_lo:.3f}, {e5_hi:.3f}]"
        bge_ci_str = f"[{bge_lo:.3f}, {bge_hi:.3f}]"
        print(
            f"  {metric_name:<13} {e5_mean:>8.3f} {e5_ci_str:>18} "
            f"{bge_mean:>9.3f} {bge_ci_str:>18} {delta:>+7.3f} {winner:>8}"
        )

        quality_results[metric_name] = {
            "e5_mean": e5_mean,
            "e5_ci": [e5_lo, e5_hi],
            "bge_mean": bge_mean,
            "bge_ci": [bge_lo, bge_hi],
            "delta": delta,
            "winner": winner,
        }

    # ── Jaccard / Agreement ────────────────────────────────────────────
    print(f"\n{'='*80}")
    print("INTER-MODEL AGREEMENT (Jaccard overlap)")
    print(f"{'='*80}\n")

    jaccard_results = {}
    for k in K_VALUES:
        jac_vals = [
            jaccard(e5_all_retrieved[i], bge_all_retrieved[i], k)
            for i in range(n_queries)
        ]
        jac_mean, jac_lo, jac_hi = bootstrap_ci(jac_vals)
        print(f"  Jaccard@{k}: {jac_mean:.3f} [{jac_lo:.3f}, {jac_hi:.3f}]")
        jaccard_results[f"Jaccard@{k}"] = {
            "mean": jac_mean,
            "ci": [jac_lo, jac_hi],
        }

    # ── Unique results analysis ────────────────────────────────────────
    print(f"\n{'='*80}")
    print("UNIQUE RESULTS ANALYSIS")
    print(f"{'='*80}\n")

    for k in K_VALUES:
        e5_only_counts = []
        bge_only_counts = []
        common_counts = []
        for i in range(n_queries):
            e5_set = set(e5_all_retrieved[i][:k])
            bge_set = set(bge_all_retrieved[i][:k])
            e5_only_counts.append(len(e5_set - bge_set))
            bge_only_counts.append(len(bge_set - e5_set))
            common_counts.append(len(e5_set & bge_set))
        print(
            f"  K={k}: E5-only={np.mean(e5_only_counts):.1f}  "
            f"BGE-only={np.mean(bge_only_counts):.1f}  "
            f"Common={np.mean(common_counts):.1f}"
        )

    # ── Performance benchmark ──────────────────────────────────────────
    print(f"\n{'='*80}")
    print("PERFORMANCE BENCHMARK")
    print(f"{'='*80}\n")

    # Use a subset of queries for multi-run performance measurement
    perf_queries = [q["query"] for q in queries_data[:PERF_QUERIES]]

    perf_results = {}
    for model_id in ["multilingual-e5-small", "bge-m3"]:
        m = model_components[model_id]
        cfg = m["cfg"]

        # Warmup
        print(f"  {cfg.id}: warming up ({PERF_WARMUP} queries)...")
        for q in perf_queries[:PERF_WARMUP]:
            embed_query(q, cfg, m["session"], m["tokenizer"])

        # Multi-run measurement
        all_embed_ms: list[float] = []
        all_search_ms: list[float] = []
        all_total_ms: list[float] = []

        for _run in range(PERF_RUNS):
            run_embed: list[float] = []
            run_search: list[float] = []
            run_total: list[float] = []
            for q in perf_queries:
                t0 = time.perf_counter()
                vec = embed_query(q, cfg, m["session"], m["tokenizer"])
                t1 = time.perf_counter()
                vector_search(cur, cfg.model_name, vec)
                t2 = time.perf_counter()
                run_embed.append((t1 - t0) * 1000)
                run_search.append((t2 - t1) * 1000)
                run_total.append((t2 - t0) * 1000)
            all_embed_ms.extend(run_embed)
            all_search_ms.extend(run_search)
            all_total_ms.extend(run_total)

        # Batch throughput
        batch_texts = perf_queries[:10]
        if cfg.passage_prefix:
            batch_texts = [cfg.passage_prefix + t for t in batch_texts]
        t0 = time.perf_counter()
        for _ in range(3):
            inputs = m["tokenizer"](
                batch_texts, padding=True, truncation=True,
                max_length=cfg.max_input_tokens, return_tensors="np",
            )
            valid = {inp.name for inp in m["session"].get_inputs()}
            ort_inputs = {k2: v for k2, v in inputs.items() if k2 in valid}
            if "token_type_ids" in valid and "token_type_ids" not in ort_inputs:
                ort_inputs["token_type_ids"] = np.zeros_like(
                    inputs["input_ids"],
                )
            m["session"].run(None, ort_inputs)
        t1 = time.perf_counter()
        batch_time = (t1 - t0) / 3
        throughput = len(batch_texts) / batch_time

        perf_results[model_id] = {
            "embedding_ms": {
                "mean": float(np.mean(all_embed_ms)),
                "p50": percentile(all_embed_ms, 0.5),
                "p95": percentile(all_embed_ms, 0.95),
                "p99": percentile(all_embed_ms, 0.99),
            },
            "search_ms": {
                "mean": float(np.mean(all_search_ms)),
                "p50": percentile(all_search_ms, 0.5),
                "p95": percentile(all_search_ms, 0.95),
                "p99": percentile(all_search_ms, 0.99),
            },
            "total_ms": {
                "mean": float(np.mean(all_total_ms)),
                "p50": percentile(all_total_ms, 0.5),
                "p95": percentile(all_total_ms, 0.95),
                "p99": percentile(all_total_ms, 0.99),
            },
            "throughput_qps": throughput,
            "device": m["device"],
        }

        print(f"  {cfg.id} ({cfg.dimension}d, {m['device']}):")
        ep = perf_results[model_id]["embedding_ms"]
        sp = perf_results[model_id]["search_ms"]
        tp = perf_results[model_id]["total_ms"]
        e_str = f"mean={ep['mean']:.1f} p50={ep['p50']:.1f} p95={ep['p95']:.1f} p99={ep['p99']:.1f}"
        s_str = f"mean={sp['mean']:.1f} p50={sp['p50']:.1f} p95={sp['p95']:.1f} p99={sp['p99']:.1f}"
        t_str = f"mean={tp['mean']:.1f} p50={tp['p50']:.1f} p95={tp['p95']:.1f} p99={tp['p99']:.1f}"
        print(f"    Embed:  {e_str}ms")
        print(f"    Search: {s_str}ms")
        print(f"    Total:  {t_str}ms")
        print(f"    Throughput: {throughput:.1f} queries/sec")

    # ── Final comparison table ─────────────────────────────────────────
    print(f"\n{'='*80}")
    print("FINAL COMPARISON TABLE")
    print(f"{'='*80}\n")

    e5_perf = perf_results["multilingual-e5-small"]
    bge_perf = perf_results["bge-m3"]

    table_header = f"{'Metric':<25} {'E5-small':>12} {'BGE-M3':>12} {'Winner':>10}"
    print(table_header)
    print("-" * len(table_header))

    # Quality metrics
    for metric_name in sorted(quality_results.keys()):
        r = quality_results[metric_name]
        print(
            f"  {metric_name:<23} {r['e5_mean']:>10.3f}  "
            f"{r['bge_mean']:>10.3f}  {r['winner']:>10}"
        )

    print()

    # Latency metrics
    for label, key in [
        ("Embed mean", "embedding_ms"),
        ("Embed p50", "embedding_ms"),
        ("Embed p95", "embedding_ms"),
        ("Search mean", "search_ms"),
        ("Search p50", "search_ms"),
        ("Search p95", "search_ms"),
        ("Total mean", "total_ms"),
        ("Total p50", "total_ms"),
        ("Total p95", "total_ms"),
    ]:
        stat = label.split()[-1].lower()
        e5_v = e5_perf[key][stat]
        bge_v = bge_perf[key][stat]
        winner = "E5" if e5_v < bge_v else "BGE"
        print(
            f"  {label:<23} {e5_v:>9.1f}ms  {bge_v:>9.1f}ms  {winner:>10}"
        )

    print()
    e5_qps = e5_perf["throughput_qps"]
    bge_qps = bge_perf["throughput_qps"]
    winner = "E5" if e5_qps > bge_qps else "BGE"
    print(f"  {'Throughput':<23} {e5_qps:>9.1f}/s  {bge_qps:>9.1f}/s  {winner:>10}")

    # Speed ratio
    print()
    print("  Speed ratio (BGE/E5):")
    print(
        f"    Embedding: {bge_perf['embedding_ms']['mean'] / e5_perf['embedding_ms']['mean']:.1f}x"
    )
    print(
        f"    Search:    {bge_perf['search_ms']['mean'] / e5_perf['search_ms']['mean']:.1f}x"
    )
    print(
        f"    Total:     {bge_perf['total_ms']['mean'] / e5_perf['total_ms']['mean']:.1f}x"
    )

    # ── Save results ───────────────────────────────────────────────────
    results = {
        "dataset": EVAL_DATASET_PATH,
        "corpus": dataset["corpus"],
        "models": {
            "e5-small": {
                "model": "intfloat/multilingual-e5-small",
                "dimension": 384,
            },
            "bge-m3": {
                "model": "BAAI/bge-m3",
                "dimension": 1024,
            },
        },
        "quality": quality_results,
        "jaccard": jaccard_results,
        "performance": perf_results,
        "n_queries": n_queries,
        "k_values": K_VALUES,
    }

    with open(OUTPUT_PATH, "w", encoding="utf-8") as f:
        json.dump(results, f, indent=2)
    print(f"\nResults saved to {OUTPUT_PATH}")

    cur.close()
    conn.close()


if __name__ == "__main__":
    main()
